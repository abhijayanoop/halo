// Generates TypeScript types from the JSON Schemas the Python side exports
// (`uv run python -m halo.core.export_schemas` writes ../schemas).
import { mkdir, readdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compileFromFile } from "json-schema-to-typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemas = join(root, "..", "schemas");
const out = join(root, "src", "types", "generated");

await mkdir(out, { recursive: true });
const files = (await readdir(schemas)).filter((f) => f.endsWith(".schema.json")).sort();
const banner = "// Generated by `npm run gen:types` from ../schemas. Do not edit.";
const names = [];
for (const file of files) {
  const name = file.replace(".schema.json", "");
  const ts = await compileFromFile(join(schemas, file), {
    bannerComment: banner,
    additionalProperties: false,
    unreachableDefinitions: false,
  });
  await writeFile(join(out, `${name}.ts`), ts);
  names.push(name);
}
await writeFile(
  join(out, "index.ts"),
  `${banner}\n${names.map((n) => `export type { ${n} } from "./${n}";`).join("\n")}\n`,
);
console.log(`generated ${names.length} types in ${out}`);
